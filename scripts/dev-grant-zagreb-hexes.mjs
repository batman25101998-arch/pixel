import { PrismaClient } from "@prisma/client";
import { cellArea, cellToLatLng, gridDisk, gridRingUnsafe, latLngToCell, UNITS } from "h3-js";
import { writeFileSync } from "node:fs";

const TARGET_EMAIL = "batman25101998@gmail.com";
const H3_RESOLUTION = 5;
const TARGET_HEX_COUNT = 5000;
const ZAGREB = { latitude: 45.815, longitude: 15.981 };
const GRANT_KEY = "dev-zagreb-5000";
const prisma = new PrismaClient();

function assertDevelopmentOnly() {
  const productionSignals = [
    process.env.NODE_ENV === "production",
    process.env.VERCEL === "1",
    process.env.RAILWAY_ENVIRONMENT_NAME?.toLowerCase() === "production"
  ];
  if (productionSignals.some(Boolean) || process.env.ALLOW_DEV_HEX_GRANT !== "true") {
    throw new Error("Development grant blocked. Set ALLOW_DEV_HEX_GRANT=true in a non-production environment.");
  }
}

function generateConnectedCells() {
  const center = latLngToCell(ZAGREB.latitude, ZAGREB.longitude, H3_RESOLUTION);
  const innerDisk = gridDisk(center, 40);
  const outerSegment = gridRingUnsafe(center, 41).slice(0, TARGET_HEX_COUNT - innerDisk.length);
  const indexes = [...innerDisk, ...outerSegment];
  if (indexes.length !== TARGET_HEX_COUNT || new Set(indexes).size !== TARGET_HEX_COUNT) {
    throw new Error(`Expected ${TARGET_HEX_COUNT} unique connected cells, generated ${indexes.length}.`);
  }

  return indexes.map((h3Index) => {
    const [latitude, longitude] = cellToLatLng(h3Index);
    return {
      h3Index,
      latitude,
      longitude,
      q: Math.round((longitude + 180) * 10000),
      r: Math.round((latitude + 90) * 10000)
    };
  });
}

function territoryStatistics(cells) {
  const indexes = new Set(cells.map((cell) => cell.h3Index));
  const areaKm2 = cells.reduce((total, cell) => total + cellArea(cell.h3Index, UNITS.km2), 0);
  const borderEdges = cells.reduce(
    (total, cell) => total + gridDisk(cell.h3Index, 1).filter((neighbor) => neighbor !== cell.h3Index && !indexes.has(neighbor)).length,
    0
  );
  return {
    hexCount: cells.length,
    areaKm2: Number(areaKm2.toFixed(2)),
    borderEdges,
    totalValueCents: cells.length * 100,
    averageValueCents: 100
  };
}

function territoryLevel(count) {
  if (count >= 5000) return "EMPIRE";
  if (count >= 1000) return "KINGDOM";
  if (count >= 100) return "CITY";
  return "VILLAGE";
}

function generateSql(cells) {
  const values = cells.map((cell) =>
    `  ('${cell.h3Index}', ${cell.q}, ${cell.r}, ${cell.latitude}, ${cell.longitude})`
  ).join(",\n");
  const statistics = JSON.stringify(territoryStatistics(cells)).replaceAll("'", "''");
  return `-- Generated by scripts/dev-grant-zagreb-hexes.mjs --write-sql
-- Development only. Run with PGOPTIONS='-c app.environment=development'.
BEGIN;

DO $$
BEGIN
  IF current_setting('app.environment', true) IS DISTINCT FROM 'development' THEN
    RAISE EXCEPTION 'Development grant blocked. Set app.environment=development.';
  END IF;
END $$;

CREATE TEMP TABLE _dev_grant_user ON COMMIT DROP AS
SELECT id FROM users WHERE email = '${TARGET_EMAIL}'::citext;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM _dev_grant_user) THEN
    RAISE EXCEPTION 'User not found: ${TARGET_EMAIL}';
  END IF;
END $$;

CREATE TEMP TABLE _dev_zagreb_cells (
  h3_index VARCHAR(32) PRIMARY KEY,
  q INTEGER NOT NULL,
  r INTEGER NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL
) ON COMMIT DROP;

INSERT INTO _dev_zagreb_cells (h3_index, q, r, latitude, longitude) VALUES
${values};

CREATE TEMP TABLE _dev_affected_territories ON COMMIT DROP AS
SELECT DISTINCT territory_id AS id
FROM hexes
WHERE h3_index IN (SELECT h3_index FROM _dev_zagreb_cells)
  AND territory_id IS NOT NULL;

UPDATE marketplace
SET active = false, status = 'CANCELED', updated_at = now()
WHERE hex_id IN (
  SELECT id FROM hexes WHERE h3_index IN (SELECT h3_index FROM _dev_zagreb_cells)
) AND active = true;

INSERT INTO hexes (
  h3_index, resolution, q, r, latitude, longitude, owner_id,
  territory_id, purchase_date, price_cents, status, created_at, updated_at
)
SELECT c.h3_index, ${H3_RESOLUTION}, c.q, c.r, c.latitude, c.longitude, u.id,
       NULL, now(), 100, 'OWNED', now(), now()
FROM _dev_zagreb_cells c CROSS JOIN _dev_grant_user u
ON CONFLICT (h3_index) DO UPDATE SET
  resolution = EXCLUDED.resolution,
  q = EXCLUDED.q,
  r = EXCLUDED.r,
  latitude = EXCLUDED.latitude,
  longitude = EXCLUDED.longitude,
  owner_id = EXCLUDED.owner_id,
  territory_id = NULL,
  purchase_date = now(),
  price_cents = 100,
  status = 'OWNED',
  updated_at = now();

INSERT INTO territories (
  owner_id, name, slug, flag, description, color, level,
  statistics, status, hex_count, created_at, updated_at
)
SELECT u.id,
       'Zagreb Development Empire',
       'dev-zagreb-empire-' || left(replace(u.id::text, '-', ''), 8),
       'DEV',
       'Development-only connected grant around Zagreb.',
       '#22c55e',
       'EMPIRE',
       '${statistics}'::jsonb,
       'ACTIVE',
       ${TARGET_HEX_COUNT},
       now(),
       now()
FROM _dev_grant_user u
ON CONFLICT (slug) DO UPDATE SET
  owner_id = EXCLUDED.owner_id,
  level = 'EMPIRE',
  statistics = EXCLUDED.statistics,
  status = 'ACTIVE',
  hex_count = ${TARGET_HEX_COUNT},
  updated_at = now();

UPDATE hexes h
SET territory_id = t.id, updated_at = now()
FROM territories t CROSS JOIN _dev_grant_user u
WHERE h.h3_index IN (SELECT h3_index FROM _dev_zagreb_cells)
  AND t.slug = 'dev-zagreb-empire-' || left(replace(u.id::text, '-', ''), 8);

UPDATE territories t
SET hex_count = (SELECT count(*)::integer FROM hexes h WHERE h.territory_id = t.id),
    level = CASE
      WHEN (SELECT count(*) FROM hexes h WHERE h.territory_id = t.id) >= 5000 THEN 'EMPIRE'::territory_level
      WHEN (SELECT count(*) FROM hexes h WHERE h.territory_id = t.id) >= 1000 THEN 'KINGDOM'::territory_level
      WHEN (SELECT count(*) FROM hexes h WHERE h.territory_id = t.id) >= 100 THEN 'CITY'::territory_level
      ELSE 'VILLAGE'::territory_level
    END,
    statistics = jsonb_build_object(
      'hexCount', (SELECT count(*) FROM hexes h WHERE h.territory_id = t.id),
      'totalValueCents', COALESCE((SELECT sum(price_cents) FROM hexes h WHERE h.territory_id = t.id), 0),
      'averageValueCents', COALESCE((SELECT round(avg(price_cents)) FROM hexes h WHERE h.territory_id = t.id), 0)
    ),
    updated_at = now()
WHERE t.id IN (SELECT id FROM _dev_affected_territories)
  AND t.id NOT IN (
    SELECT t2.id FROM territories t2 CROSS JOIN _dev_grant_user u
    WHERE t2.slug = 'dev-zagreb-empire-' || left(replace(u.id::text, '-', ''), 8)
  );

UPDATE users
SET kingdom_unlocked_at = COALESCE(kingdom_unlocked_at, now()), updated_at = now()
WHERE id IN (SELECT id FROM _dev_grant_user)
  AND (SELECT count(*) FROM hexes WHERE owner_id = users.id) >= 1000;

INSERT INTO badges (user_id, type)
SELECT u.id, badge.type::badge_type
FROM _dev_grant_user u
CROSS JOIN (VALUES
  ('FIRST_HEX'), ('VILLAGE_OWNER'), ('CITY_BUILDER'), ('KINGDOM_FOUNDER'), ('COLLECTOR_100')
) AS badge(type)
ON CONFLICT (user_id, type) DO NOTHING;

INSERT INTO transactions (
  hex_id, buyer_id, type, status, amount, platform_fee_cents,
  currency, metadata, created_at, completed_at
)
SELECT h.id, u.id, 'ADMIN_ADJUSTMENT', 'COMPLETED', 100, 0,
       'usd', '{"grant":"${GRANT_KEY}","developmentOnly":true}'::jsonb, now(), now()
FROM hexes h
CROSS JOIN _dev_grant_user u
WHERE h.h3_index IN (SELECT h3_index FROM _dev_zagreb_cells)
  AND NOT EXISTS (
    SELECT 1 FROM transactions tr
    WHERE tr.hex_id = h.id
      AND tr.type = 'ADMIN_ADJUSTMENT'
      AND tr.metadata->>'grant' = '${GRANT_KEY}'
  );

COMMIT;
`;
}

async function recalculateAffectedTerritories(tx, territoryIds) {
  for (const id of territoryIds) {
    const remaining = await tx.hex.findMany({ where: { territoryId: id }, select: { h3Index: true, priceCents: true } });
    const totalValueCents = remaining.reduce((sum, hex) => sum + Number(hex.priceCents), 0);
    await tx.territory.update({
      where: { id },
      data: {
        hexCount: remaining.length,
        level: territoryLevel(remaining.length),
        statistics: {
          hexCount: remaining.length,
          totalValueCents,
          averageValueCents: remaining.length ? Math.round(totalValueCents / remaining.length) : 0
        }
      }
    });
  }
}

async function main() {
  const cells = generateConnectedCells();
  if (process.argv.includes("--write-sql")) {
    const output = new URL("./dev-grant-zagreb-hexes.sql", import.meta.url);
    writeFileSync(output, generateSql(cells), "utf8");
    console.log(`Generated ${output.pathname}`);
    return;
  }
  assertDevelopmentOnly();
  const indexes = cells.map((cell) => cell.h3Index);
  const user = await prisma.user.findUnique({ where: { email: TARGET_EMAIL }, select: { id: true, email: true } });
  if (!user) throw new Error(`User not found: ${TARGET_EMAIL}`);

  const result = await prisma.$transaction(async (tx) => {
    const existing = await tx.hex.findMany({
      where: { h3Index: { in: indexes } },
      select: { h3Index: true, ownerId: true, territoryId: true }
    });
    const existingIndexes = new Set(existing.map((hex) => hex.h3Index));
    const affectedTerritoryIds = new Set(existing.flatMap((hex) => hex.territoryId ? [hex.territoryId] : []));
    const changedIndexes = new Set(existing.filter((hex) => hex.ownerId !== user.id).map((hex) => hex.h3Index));
    for (const cell of cells) if (!existingIndexes.has(cell.h3Index)) changedIndexes.add(cell.h3Index);

    await tx.hex.createMany({
      data: cells.filter((cell) => !existingIndexes.has(cell.h3Index)).map((cell) => ({
        ...cell,
        resolution: H3_RESOLUTION,
        ownerId: user.id,
        status: "OWNED",
        priceCents: 100,
        purchaseDate: new Date()
      })),
      skipDuplicates: true
    });
    await tx.hex.updateMany({
      where: { h3Index: { in: indexes } },
      data: {
        ownerId: user.id,
        territoryId: null,
        status: "OWNED",
        priceCents: 100,
        purchaseDate: new Date()
      }
    });

    const grantedHexes = await tx.hex.findMany({ where: { h3Index: { in: indexes } }, select: { id: true, h3Index: true } });
    await tx.marketplaceListing.updateMany({
      where: { hexId: { in: grantedHexes.map((hex) => hex.id) }, active: true },
      data: { active: false, status: "CANCELED" }
    });

    const slug = `dev-zagreb-empire-${user.id.replaceAll("-", "").slice(0, 8)}`;
    const statistics = territoryStatistics(cells);
    const territory = await tx.territory.upsert({
      where: { slug },
      create: {
        ownerId: user.id,
        name: "Zagreb Development Empire",
        slug,
        flag: "DEV",
        description: "Development-only connected grant around Zagreb.",
        color: "#22c55e",
        level: "EMPIRE",
        status: "ACTIVE",
        hexCount: TARGET_HEX_COUNT,
        statistics
      },
      update: { ownerId: user.id, level: "EMPIRE", status: "ACTIVE", hexCount: TARGET_HEX_COUNT, statistics }
    });
    await tx.hex.updateMany({ where: { h3Index: { in: indexes } }, data: { territoryId: territory.id } });
    affectedTerritoryIds.delete(territory.id);
    await recalculateAffectedTerritories(tx, affectedTerritoryIds);

    await tx.user.update({ where: { id: user.id }, data: { kingdomUnlockedAt: new Date() } });
    await Promise.all(["FIRST_HEX", "VILLAGE_OWNER", "CITY_BUILDER", "KINGDOM_FOUNDER", "COLLECTOR_100"].map((type) =>
      tx.badge.upsert({ where: { userId_type: { userId: user.id, type } }, create: { userId: user.id, type }, update: {} })
    ));

    const transactionHexes = grantedHexes.filter((hex) => changedIndexes.has(hex.h3Index));
    if (transactionHexes.length) {
      await tx.transaction.createMany({
        data: transactionHexes.map((hex) => ({
          hexId: hex.id,
          buyerId: user.id,
          type: "ADMIN_ADJUSTMENT",
          status: "COMPLETED",
          amount: 100,
          completedAt: new Date(),
          metadata: { grant: GRANT_KEY, developmentOnly: true }
        }))
      });
    }

    return {
      territoryId: territory.id,
      territoryCount: await tx.territory.count({ where: { ownerId: user.id, status: "ACTIVE" } }),
      ownedHexCount: await tx.hex.count({ where: { ownerId: user.id } }),
      grantedHexCount: grantedHexes.length,
      transactionsCreated: transactionHexes.length
    };
  }, { maxWait: 10_000, timeout: 120_000 });

  console.log(JSON.stringify({ email: user.email, resolution: H3_RESOLUTION, kingdomUnlocked: true, ...result }, null, 2));
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
